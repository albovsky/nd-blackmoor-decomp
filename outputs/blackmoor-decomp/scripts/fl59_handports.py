#!/usr/bin/env python3
"""FL-59: the three upper rows that no lifter could take, as "translated, unverified" (NOT port credits; the mutation check was not run).

  0x50ed50, 0x50fa90   the CRT memmove (two copies of the same code, different jump tables inside the code): hand ports with the semantics of memmove
  0x4d8dca             quicksort of the pointer array at this+0x980c by the key at [element + 0x100] (recursive, thiscall, ret 8): the BULK lift with the two self-calls run natively

  fl59_handports.py [--scenarios 400] [--write]      (run from outputs/blackmoor-decomp)

It builds translated/original_methods_fl59_handports.c, runs every row on the original bytes (Unicorn) and on the C and compares what is observable at the call boundary:
  memmove rows   eax, esp, ebx, ebp, esi, edi and the final content of every written cell (the original writes dwords and bytes in an order that depends on the alignment, the port writes bytes;
                 ecx, edx and the flags are scratch registers of the original that the caller never reads and are not modelled)
  0x4d8dca       the whole digest of tests/fl41_world.py (all registers, the ordered writes, the ordered callee calls), because that row is a straight translation
Scenarios for the memmove rows: constructed (dst, src, n) triples that cover every alignment of both pointers, n from 0 to 80 and a few larger, forward and backward overlaps, plus the natural seeds that do not fault.
With --write it records the agreeing scenarios in tests/fl59_handports.json.
"""
import argparse
import ctypes
import json
from pathlib import Path
import random
import sys
import tempfile

sys.dont_write_bytecode = True
PROJECT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(PROJECT / 'tests'))
sys.path.insert(0, str(PROJECT / 'scripts'))
import fl41_world as W
import lift_fl41 as L

OUT = PROJECT / 'translated/original_methods_fl59_handports.c'
TABLE = PROJECT / 'tests/fl59_handports.json'
MEMMOVE = {0x50ed50: 664, 0x50fa90: 664}

HEADER = '''/* FL-59: GAME.EXE functions at or above 0x480000 that no lifter could translate, translated by hand or by the BULK lifter plus one edit WITHOUT the mutation check
 * ("translated, unverified": these are not port credits). GENERATED by scripts/fl59_handports.py; do not edit by hand. Each symbol `m<va>_lifted` is the original function at <va>. */
#include "original_methods_fl41.h"
'''

MEMMOVE_C = '''
/* GAME.EXE 0x%(va)x (%(size)d bytes): the CRT memmove, hand port. cdecl: dst [esp+4], src [esp+8], n [esp+0xc]; copies n bytes so that overlapping blocks come out right and returns dst in eax.
 * The original copies forward (unaligned head bytes, dwords, tail bytes through jump tables that sit inside the code) when dst <= src or dst >= src + n, else backward from the end; the result in
 * memory is the same as a byte-by-byte copy in that direction. esi, edi and ebp are saved and restored. ecx, edx and the flags are scratch in the original and are not modelled. */
void m%(va)x_lifted(Fl41Regs *r, const Fl41Host *h)
{
    FL41_PROLOGUE
    uint32_t dst = RD32((uint32_t)(esp + 4u)), src = RD32((uint32_t)(esp + 8u)), n = RD32((uint32_t)(esp + 12u)), k;
    if (dst <= src || dst >= (uint32_t)(src + n)) {
        for (k = 0; k < n; k++)
            WR8((uint32_t)(dst + k), RD8((uint32_t)(src + k)));
    } else {
        for (k = n; k > 0; k--)
            WR8((uint32_t)(dst + k - 1u), RD8((uint32_t)(src + k - 1u)));
    }
    eax = dst;
    esp += 4u;
    FL41_EPILOGUE
}
'''


def quicksort_c():
    L.BULK = True
    try:
        text = L.lift(0x4d8dca, 320)[0]
    finally:
        L.BULK = False
    old = 'FL41_CALL(0x4d8dcau); esp += 8u; esp += 4u;'
    assert text.count(old) == 2
    # the callee pops its own two arguments (`ret 8`), so after the lifted self-call esp is already past them
    return '\n' + text.replace(old, 'FL41_CALL_LIFTED(m4d8dca_lifted);').replace('/* GAME.EXE 0x4d8dca (320 bytes): machine translation of the original instructions, see the note at the top of this file. */',
                                                                                  '/* GAME.EXE 0x4d8dca (320 bytes): quicksort, translated by scripts/lift_fl41.py (BULK) with the two recursive calls run natively through FL41_CALL_LIFTED instead of the host. */')


def source():
    return HEADER + ''.join(MEMMOVE_C % {'va': va, 'size': size} for va, size in sorted(MEMMOVE.items())) + quicksort_c()


def row_for(va):
    size = MEMMOVE.get(va, 320)
    return W.row_info(va, size, {})


def memmove_scenarios(count):
    base = W.REGION_BASE
    rng = random.Random(59)
    out = []
    for n in list(range(0, 41)) + [47, 48, 63, 64, 65, 100, 127, 128, 129, 200, 255, 256, 300]:
        for dst_al in range(4):
            out.append((base + 0x100 + dst_al, base + 0x2000, n))        # disjoint, every destination alignment (source aligned)
        for src_al in range(1, 4):
            out.append((base + 0x100, base + 0x2000 + src_al, n))
    while len(out) < count:
        n = rng.choice((rng.randrange(0, 40), rng.randrange(0, 300)))
        d = base + 0x1000 + rng.randrange(0, 64)
        s = d + rng.randrange(-40, 41)
        out.append((d, s, n))                                      # overlapping, both directions
    return [(d, s, n) for d, s, n in out]


def stack_overrides(dst, src, n):
    return ((W.SP + 4, 4, dst), (W.SP + 8, 4, src), (W.SP + 12, 4, n))


def memmove_view(t):
    mem = {}
    for address, size, value in t.writes:
        if W.STACK_BASE <= address < W.STACK_BASE + W.STACK_SIZE:
            continue        # the original's push/pop of ebp, edi and esi
        for b in range(size):
            mem[address + b] = (value >> (8 * b)) & 0xff
    return ({k: t.regs[k] for k in ('eax', 'ebx', 'esp', 'ebp', 'esi', 'edi')}, sorted(mem.items()), t.fault)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--scenarios', type=int, default=400)
    ap.add_argument('--seeds', type=int, default=40)
    ap.add_argument('--write', action='store_true')
    a = ap.parse_args()
    text = source()
    OUT.write_text(text)
    table = {}
    with tempfile.TemporaryDirectory() as tmp:
        lib = W.build_library(tmp, [OUT])
        for va in sorted(MEMMOVE):
            row = row_for(va)
            kept, bad = [], 0
            for d, s, n in memmove_scenarios(a.scenarios):
                ov = stack_overrides(d, s, n)
                original = W.run_original(row, 0, ov)
                if original.fault:
                    continue
                native = W.run_native(lib, row, 0, ov)
                if memmove_view(native) == memmove_view(original):
                    kept.append([d, s, n])
                else:
                    bad += 1
            natural = []
            for seed in range(a.seeds):
                original = W.run_original(row, seed)
                if original.fault:
                    continue
                native = W.run_native(lib, row, seed)
                if memmove_view(native) == memmove_view(original):
                    natural.append(seed)
                else:
                    bad += 1
            print('0x%x memmove: %d constructed scenarios agree, %d natural seeds agree, %d disagree' % (va, len(kept), len(natural), bad))
            assert not bad
            table['0x%x' % va] = {'kind': 'memmove', 'body': MEMMOVE[va], 'scenarios': kept[:60], 'seeds': natural, 'scenarios_checked': len(kept), 'compared': 'eax esp ebx ebp esi edi and the final content of written cells'}
        row = row_for(0x4d8dca)
        seeds, bad = [], 0
        for seed in range(400):
            original = W.run_original(row, seed)
            if original.fault or len(original.writes) < 2:
                continue
            native = W.run_native(lib, row, seed)
            if native.digest() == original.digest():
                seeds.append(seed)
            else:
                bad += 1
            if len(seeds) >= 12:
                break
        print('0x4d8dca quicksort: %d seeds agree (full digest), %d disagree' % (len(seeds), bad))
        assert seeds and not bad
        table['0x4d8dca'] = {'kind': 'quicksort', 'body': 320, 'seeds': seeds, 'compared': 'full digest (registers, ordered writes, ordered calls)'}
    if a.write:
        TABLE.write_text(json.dumps(table, indent=1, sort_keys=True) + '\n')


if __name__ == '__main__':
    main()
