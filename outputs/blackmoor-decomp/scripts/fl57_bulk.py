#!/usr/bin/env python3
"""FL-57: bulk translation of the upper rows that scripts/fl55_bulk.py's lifter refused (tasks/fl55-translation-defects.json `refused`), WITHOUT the mutation check and without a coverage search.

The lifter is scripts/lift_fl41.py in BULK mode with the FL-57 extensions (non-ledger callees with the pop of their first `ret`, callees that write esp, a conditional or indirect jump out of the function
as a tail call, recursion, `lock`, sahf/lahf, rcl/rcr, shld/shrd, xlatb, and x87: fldz/fld1/fldpi.., fxch, fstp st(i), fnstcw/fldcw/fnclex, fnstsw to memory, 10-byte loads and stores, fist/fistp,
frndint, fabs, fsqrt, fsin, fcos, f2xm1, fprem, fprem1, fpatan, fyl2x, fscale, fxam). Each translation is compiled with the others and run, for a few seeds, against the original bytes (Unicorn) with the
same quick comparison as fl55_bulk.py. A row is recorded as `agrees` (a seed ran in the original and the translation agrees on every seed that did), `no seed`, or listed under `failed`
(mismatch / error: a lifter defect to fix). NOT a port credit: the ledger does not change.

  translated/original_methods_fl57_translated.c   one `m<va>_lifted` per row that agrees or has no seed (never linked into the app)
  tests/fl57_translated.json                      per row: body, callees, imports, fs, kept seeds, coverage, status, and what the lifter guessed
  tasks/fl57-translation-defects.json             rows still refused by the lifter, and rows that failed the comparison

  fl57_bulk.py [--rows 0x...,0x...] [--seeds 8] [--jobs 4] [--timeout 40] [--cache FILE] [--out-dir DIR]      (run from outputs/blackmoor-decomp)
"""
from __future__ import annotations

import argparse
import json
import multiprocessing as mp
from pathlib import Path
import re
import sys
import tempfile
import time

sys.dont_write_bytecode = True
PROJECT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(PROJECT / 'tests'))
sys.path.insert(0, str(PROJECT / 'scripts'))
import fl41_world as W
import lift_fl41 as L
import fl55_bulk as B

HEADER = '''/* FL-57: GAME.EXE functions at or above 0x480000 that the FL-55b lifter refused, translated instruction by instruction by scripts/lift_fl41.py (BULK mode) WITHOUT the mutation check
 * ("translated, unverified": these are not port credits). GENERATED by scripts/fl57_bulk.py; do not edit by hand. Each symbol `m<va>_lifted` is the original function at <va>. */
#include "original_methods_fl41.h"
'''
REFUSED = PROJECT / 'tasks/fl55-translation-defects.json'


def sizes_for(va):
    """the span of the ledger (the code up to the next function start: a tail jump past the Ghidra body stays inside), then the body size, then (for code that ends in a data table or in a partial instruction) the part that decodes"""
    e = L.ledger_entry(va)
    sizes = [e['span'], e['body_size'] or e['span']]
    for sz in list(sizes):
        try:
            L.disasm(va, sz)
        except L.Unsupported as ex:
            m = re.search(r'stops at (0x[0-9a-f]+)', str(ex))
            if m and int(m.group(1), 16) > va:
                sizes.append(int(m.group(1), 16) - va)
    return list(dict.fromkeys(sizes))


def one(args):
    """fl55_bulk.one, and a row whose original does not leave esp at the return address + its own `ret N` (an EH epilog that restores esp from its frame, a fragment that jumps on) is compared without that rule"""
    row, libpath, seeds, timeout = args
    va, res = B.one(args)
    if res['status'] == 'mismatch' and res.get('detail') == 'stack discipline after the original run':
        row = dict(row, ret=[])
        va, res = B.one((row, libpath, seeds, timeout))
        if res['status'] in ('complete', 'incomplete'):
            res['stack_rule'] = 'skipped'
    return va, res


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--rows')
    ap.add_argument('--seeds', type=int, default=8)
    ap.add_argument('--jobs', type=int, default=4)
    ap.add_argument('--timeout', type=int, default=40)
    ap.add_argument('--cache')
    ap.add_argument('--out-dir', default=str(PROJECT))
    a = ap.parse_args()
    L.BULK = True
    spans = L.ledger_spans()
    todo_rows = sorted(int(k, 16) for k in json.loads(REFUSED.read_text())['refused']) if not a.rows else [int(v, 16) for v in a.rows.split(',')]
    texts, rows, extra, refused = {}, {}, {}, {}
    uses_inline = False
    for va in todo_rows:
        last = None
        for size in sizes_for(va):
            L.GUESSED_CALLEES.clear()
            L.ASSUMED_MATH.clear()
            L._FPU_NET.clear()
            L._FPU_NET_BULK.clear()
            try:
                text, callees, imports, fs, inline = L.lift(va, size)
            except L.Unsupported as ex:
                last = str(ex)
                continue
            except Exception as ex:                       # noqa: BLE001
                last = 'lifter error: %s: %s' % (type(ex).__name__, str(ex)[:120])
                continue
            uses_inline |= bool(inline)
            texts[va] = text
            rows[va] = W.row_info(va, size, callees, imports, fs)
            rows[va]['indirect'] = 'FL41_CALL(t_)' in text or 'FL41_CALL(0x%xu)' % va in text or bool(L.GUESSED_CALLEES) or bool(re.search(r'FL41_CALL\(0x[0-9a-f]+u\); esp \+= \d+u; goto done;', text))    # the original runs real code where the translation has a stub (a callee fragment, a tail jump into another function)
            extra[va] = {'guessed_callee_pops': sorted(hex(x) for x in L.GUESSED_CALLEES), 'assumed_x87_math': {hex(k): v for k, v in sorted(L.ASSUMED_MATH.items())}}
            last = None
            break
        if last:
            refused['0x%x' % va] = last
    lifted = sorted(texts)
    print('lifted %d of %d rows; refused %d' % (len(lifted), len(todo_rows), len(refused)), flush=True)
    helper = L.lift(0x50c920, spans[0x50c920])[0] if uses_inline else ''
    results = {}
    cache = Path(a.cache) if a.cache else None
    if cache is not None and cache.is_file():
        results = {int(k, 16): v for k, v in json.loads(cache.read_text()).items()}
    todo = sorted((v for v in lifted if v not in results or (results[v]['status'] in ('error', 'mismatch') and not results[v].get('detail', '').startswith('hang'))), key=lambda v: rows[v]['body'])
    t0 = time.time()
    if todo:
        tmp = tempfile.mkdtemp()
        src = Path(tmp) / 'all.c'
        build_set = list(lifted)
        for attempt in range(6):                      # a row whose C does not compile is taken out and recorded as an error
            head = '#include "original_methods_fl41.h"\n' + L.FL57_HELPERS + helper
            lines_at, n = {}, head.count('\n') + 1
            for v in build_set:
                lines_at[v] = (n, n + texts[v].count('\n') + 1)
                n += texts[v].count('\n') + 2
            src.write_text(head + '\n'.join(texts[v] for v in build_set))
            try:
                W.build_library(tmp, [src])
                break
            except AssertionError as ex:
                bad = {v for m in re.finditer(r'all\.c:(\d+):\d+: error', str(ex)) for v, (lo, hi) in lines_at.items() if lo <= int(m.group(1)) <= hi}
                if not bad:
                    raise
                for v in bad:
                    results[v] = {'status': 'error', 'detail': 'C does not compile: ' + str(ex)[:300]}
                build_set = [v for v in build_set if v not in bad]
                todo = [v for v in todo if v not in bad]
                print('dropped %d rows that do not compile' % len(bad), flush=True)
        libpath = str(Path(tmp) / 'fl41.so')
        print('library built, %.0f s' % (time.time() - t0), flush=True)
        with mp.Pool(a.jobs, maxtasksperchild=1) as pool:
            for k, (va, res) in enumerate(pool.imap_unordered(one, [(rows[v], libpath, a.seeds, a.timeout) for v in todo])):
                results[va] = res
                if cache is not None:
                    cache.write_text(json.dumps({hex(x): y for x, y in results.items()}))
                print('%d/%d 0x%x %s %s' % (k + 1, len(todo), va, res['status'], {x: res[x] for x in ('instructions', 'directions') if x in res}), flush=True)
    done = {}
    for v in lifted:
        res = results[v]
        if res['status'] in ('complete', 'incomplete'):
            done[v] = 'agrees' if res['seeds'] else 'no seed'
    out = Path(a.out_dir)
    kept = [v for v in lifted if v in done]
    (out / 'translated/original_methods_fl57_translated.c').write_text(HEADER + L.FL57_HELPERS + helper + '\n'.join(texts[v] for v in kept))
    table = {'0x%x' % v: dict({'body': rows[v]['body'], 'callees': {hex(k): n for k, n in rows[v]['callees'].items()},
                               'imports': {hex(k): n for k, n in rows[v]['imports'].items()}, 'fs': rows[v]['fs'], 'status': done[v],
                               'seeds': [[sd, [list(o) for o in ov]] for sd, ov in results[v]['seeds']],
                               'instructions': results[v]['instructions'], 'directions': results[v]['directions'], 'stack_rule': results[v].get('stack_rule', 'checked')}, **extra[v]) for v in kept}
    (out / 'tests/fl57_translated.json').write_text(json.dumps(table, indent=1, sort_keys=True) + '\n')
    bad = {'0x%x' % v: results[v] for v in lifted if v not in done}
    (out / 'tasks/fl57-translation-defects.json').write_text(json.dumps({'refused': refused, 'failed': bad}, indent=1, sort_keys=True) + '\n')
    print('translated %d (agrees %d, no seed %d); mismatch %d, error %d; refused by the lifter %d, %.0f s'
          % (len(kept), sum(1 for v in kept if done[v] == 'agrees'), sum(1 for v in kept if done[v] == 'no seed'),
             sum(1 for r in bad.values() if r['status'] == 'mismatch'), sum(1 for r in bad.values() if r['status'] == 'error'), len(refused), time.time() - t0))


if __name__ == '__main__':
    main()
