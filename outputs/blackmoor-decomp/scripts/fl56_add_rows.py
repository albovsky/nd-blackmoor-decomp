#!/usr/bin/env python3
"""FL-56: move translated lower rows from tests/fl40_pending.json into the corpus, the C source and the differential test.

  fl56_add_rows.py ROW [ROW ...] [--scen FILE] [--untaken-ok A:dir,B:dir] [--dry]        (run from outputs/blackmoor-decomp)

For each row it runs the kept seeds of the pending entry plus the scenarios of --scen ({row: [[seed, overrides], ...]}) on the original bytes and on the translation, requires them to agree,
and requires that together they run every instruction and take every direction of every conditional jump, except the directions named by --untaken-ok (`0x42311f:taken`, an address and
`taken` or `fall-through`; these are listed in the corpus entry as `untaken_ok` and need a mechanical proof by scripts/fl56_untaken.py). Then it adds
the translation to src/original_methods_fl40.c (in address order), the corpus entry to tests/fl40_corpus.json (only the scenarios that add coverage are kept) and the test to
tests/test_fl40_differential.py (regenerated by scripts/fl40_generate.py test_source), and drops the row from tests/fl40_pending.json.
"""
import argparse
import json
from pathlib import Path
import re
import sys
import tempfile

sys.dont_write_bytecode = True
PROJECT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(PROJECT / 'tests'))
sys.path.insert(0, str(PROJECT / 'scripts'))
import fl40_world as W
import lift_function as L
import fl40_generate as G

SOURCE = PROJECT / 'src/original_methods_fl40.c'
CORPUS = PROJECT / 'tests/fl40_corpus.json'
PENDING = PROJECT / 'tests/fl40_pending.json'
TEST = PROJECT / 'tests/test_fl40_differential.py'


def split_source(text):
    head, *parts = re.split(r'(?m)^(?=/\* GAME\.EXE 0x[0-9a-f]+ \()', text)
    return head, parts


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('rows', nargs='+')
    ap.add_argument('--scen')
    ap.add_argument('--untaken-ok', default='')
    ap.add_argument('--dry', action='store_true')
    a = ap.parse_args()
    scen = json.loads(Path(a.scen).read_text()) if a.scen else {}
    ok = {}
    for item in [x for x in a.untaken_ok.split(',') if x]:
        addr, d = item.split(':')
        ok.setdefault(int(addr, 16), set()).add(d)
    corpus = json.loads(CORPUS.read_text())
    pending = json.loads(PENDING.read_text())
    spans = L.ledger_spans()
    source = SOURCE.read_text()
    head, parts = split_source(source)
    existing = [int(re.match(r'/\* GAME\.EXE (0x[0-9a-f]+)', p).group(1), 16) for p in parts]
    by_va = {int(re.match(r'/\* GAME\.EXE (0x[0-9a-f]+)', p).group(1), 16): p for p in parts}
    for key in a.rows:
        va = int(key, 16)
        text, callees, imports, fs, inline = L.lift(va, spans[va])
        assert not inline or 'm50c920_lifted' in source, 'inline helper missing'
        row = W.row_info(va, spans[va], callees, imports, fs)
        tmp = tempfile.mkdtemp()
        src = Path(tmp) / 'row.c'
        src.write_text('#include "original_methods_fl40.h"\n' + (L.lift(0x50c920, spans[0x50c920])[0] if inline else '') + '\n' + text)
        lib = W.build_library(tmp, [src])
        ex, ed, kept = set(), set(), []
        for seed, overrides in list((pending.get(key) or {}).get('seeds', [])) + list(scen.get(key, [])):
            overrides = [tuple(o) for o in overrides]
            o = W.run_original(row, seed, overrides)
            if o.fault:
                print(key, 'a scenario faults in the original: dropped')
                continue
            if o.executed <= ex and o.edges <= ed:
                continue
            n = W.run_native(lib, row, seed, overrides)
            if n.fault or n.digest() != o.digest():
                print(key, 'MISMATCH on seed', seed, overrides)
                return 1
            kept.append([seed, [list(x) for x in overrides]])
            ex |= o.executed
            ed |= o.edges
        got, total, taken, dirs, missing, untaken = G.covers(row, ex, ed)
        left = sorted((x, d) for x, d in untaken if d not in ok.get(x, ()))
        unused = sorted((x, d) for x, ds in ok.items() for d in ds if (x, d) not in set(untaken))
        print('%s instructions %d/%d directions %d/%d untaken %s' % (key, got, total, taken, dirs, [(hex(x), d) for x, d in untaken]))
        if missing or left or unused:
            print(key, 'NOT complete: never run %s, untaken not allowed %s, allowed but taken %s' % ([hex(x) for x in missing], [(hex(x), d) for x, d in left], unused))
            return 1
        entry = {'body': row['body'], 'callees': {hex(k): n for k, n in row['callees'].items()}, 'imports': {hex(k): n for k, n in row['imports'].items()}, 'fs': row['fs'],
                 'seeds': kept, 'instructions': [got, total], 'directions': [taken, dirs]}
        if untaken:
            entry['untaken_ok'] = [['0x%x' % x, d] for x, d in untaken]
        corpus[key] = entry
        by_va[va] = text + '\n'
        pending.pop(key, None)
    if a.dry:
        return 0
    order = list(existing)       # the file order stays; a new row goes in front of the first row with a higher address (the shared inline helper stays first)
    for v in sorted(set(by_va) - set(existing)):
        later = [i for i, w in enumerate(order) if w != 0x50c920 and w > v]
        order.insert(later[0] if later else len(order), v)
    SOURCE.write_text(head + ''.join(by_va[v] if by_va[v].endswith('\n') else by_va[v] + '\n' for v in order))
    CORPUS.write_text(json.dumps(corpus, indent=1, sort_keys=True) + '\n')
    PENDING.write_text(json.dumps(pending, indent=1, sort_keys=True) + '\n')
    TEST.write_text(G.test_source(sorted(int(k, 16) for k in corpus)))
    print('added', len(a.rows), 'rows')
    return 0


if __name__ == '__main__':
    sys.exit(main())
