#!/usr/bin/env python3
"""FL-55b: bulk translation of the pending rows at or above 0x480000 WITHOUT the mutation check and without the coverage search.

Every pending row of the ledger (game and library region) that scripts/lift_fl41.py takes is translated; the translation is compiled with the others and run, for a few seeds, against the original
bytes (Unicorn) with the same world and the same comparison as the credited rows (tests/fl41_world.py). A row is recorded as

  agrees       at least one seed ran in the original without a fault and the translation agrees on every seed that did (the seeds that run new instructions or edges are kept)
  no seed      every seed faulted in the original: the translation compiles and nothing more is known
  mismatch     the translation differs from the original on a seed: a lifter defect to fix (listed, not recorded as translated)
  error        the search itself failed or timed out

This is NOT a port credit: the ledger does not change. The rows are the "translated, unverified" count of the status reports. Output:

  translated/original_methods_fl41_translated.c   one `m<va>_lifted` per row that agrees or has no seed (same symbol names as the credited rows; never linked into the app)
  tests/fl41_translated.json               per row: body, callees, imports, fs, kept seeds, instructions executed/total, directions taken/total, status

  fl55_bulk.py [--rows 0x...,0x...] [--seeds 24] [--jobs 4] [--timeout 120] [--cache FILE] [--out-dir DIR]      (run from outputs/blackmoor-decomp)
"""
from __future__ import annotations

import argparse
import json
import multiprocessing as mp
from pathlib import Path
import signal
import sys
import tempfile
import time
import traceback

sys.dont_write_bytecode = True
PROJECT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(PROJECT / 'tests'))
sys.path.insert(0, str(PROJECT / 'scripts'))
import fl41_generate as G
import fl41_world as W
import lift_fl41 as L

HEADER = '''/* FL-55b: GAME.EXE functions at or above 0x480000 translated instruction by instruction by scripts/lift_fl41.py WITHOUT the mutation check ("translated, unverified": these are not port credits).
 * GENERATED by scripts/fl55_bulk.py; do not edit by hand. Each symbol `m<va>_lifted` is the original function at <va>; a function that also has a credited port is not repeated here. */
#include "original_methods_fl41.h"

void m50f978_lifted(Fl41Regs *r, const Fl41Host *h);      /* FL-58: __EH_prolog is run natively by the rows that call it (it sets ebp and moves esp, which a stub cannot) */

'''


class Timeout(Exception):
    pass


FLAG = []


def _alarm(signum, frame):
    FLAG.append(1)                                 # an exception raised inside a ctypes callback is swallowed: the flag is checked after every run
    raise Timeout()


def guarded_native(lib, row, seed, limit=15):
    """FL-58: the translation runs in a forked child with an alarm (a native loop cannot be interrupted in this process); returns (fault, digest, registers) or 'hang'"""
    import os
    import pickle
    r_fd, w_fd = os.pipe()
    pid = os.fork()
    if pid == 0:
        try:
            os.close(r_fd)
            signal.signal(signal.SIGALRM, signal.SIG_DFL)
            signal.alarm(limit)
            n = W.run_native(lib, row, seed, ())
            signal.alarm(0)
            os.write(w_fd, pickle.dumps((n.fault, n.digest(), n.regs)))
        finally:
            os._exit(0)
    os.close(w_fd)
    chunks = []
    while True:
        part = os.read(r_fd, 65536)
        if not part:
            break
        chunks.append(part)
    os.close(r_fd)
    os.waitpid(pid, 0)
    return pickle.loads(b''.join(chunks)) if chunks else 'hang'


def quick(row, libpath, seeds, timeout):
    """the first `seeds` plain seeds (and as many float seeds for an x87 row) on the original and on the translation; the seeds that run new instructions or edges are kept. A mismatch is
    reported; a timeout ends the row with what it has. A row that is the tail of a function (it reads ebp before writing it) with no usable seed is tried again with ebp on a frame (FL-58)"""
    import ctypes
    import capstone
    lib = ctypes.CDLL(libpath)
    result = _quick(row, lib, seeds, timeout)
    if result[1].get('status') in ('complete', 'incomplete') and not result[1]['seeds'] and W.frame_start(W.od.load_image(), row['va'], row['body']):
        framed = dict(row, frame=True)
        again = _quick(framed, lib, seeds, timeout)
        if again[1].get('status') in ('complete', 'incomplete') and again[1]['seeds']:
            again[1]['frame'] = True
            return again
    return result


def _quick(row, lib, seeds, timeout):
    ex, ed, kept, faults = set(), set(), [], 0
    del FLAG[:]
    order = list(range(seeds))
    if row.get('fpu'):
        order = [s for pair in zip(range(seeds), range(W.FLOAT_SEEDS, W.FLOAT_SEEDS + seeds)) for s in pair]
    signal.signal(signal.SIGALRM, _alarm)
    signal.alarm(timeout)
    status = None
    try:
        for seed in order:
            o = W.run_original(row, seed, ())
            if FLAG:
                break
            if o.fault:
                faults += 1
                continue
            # a row without `ret` (a thunk that jumps on, a fragment that ends in a call) has no stack rule; a row whose `ret` pops something else than its return address (`__EH_prolog`: push eax / ret)
            # is compared on the digest alone
            n = guarded_native(lib, row, seed)
            if FLAG:
                break
            if n == 'hang':
                status = {'status': 'mismatch', 'detail': 'hang: the translation does not return on seed %d where the original does' % seed}       # FL-58: seen on the rows 0x4933ff 0x4a1d3a 0x4adb6c 0x4ae178 of the first bulk run
                break
            if (n[0] or n[1] != o.digest()) and not row['ret']:
                continue                                   # the original runs on past the end of a fragment; the translation cannot match it: the seed says nothing
            if n[0] or n[1] != o.digest():
                status = {'status': 'mismatch', 'detail': repr(('seed', seed, o.regs, n[2], n[0]))[:600]}
                break
            if not (o.executed <= ex and o.edges <= ed):
                kept.append((seed, []))
                ex |= o.executed
                ed |= o.edges
    except Timeout:
        pass
    finally:
        signal.alarm(0)
    if status:
        return row['va'], status
    a, b, c, d, missing, untaken = G.covers(row, ex, ed)
    return row['va'], {'status': 'complete' if (a == b and c == d) else 'incomplete', 'seeds': kept, 'instructions': [a, b], 'directions': [c, d], 'faults': faults}


def one(args):
    row, libpath, seeds, timeout = args
    try:
        return quick(row, libpath, seeds, timeout)
    except BaseException as ex:                            # noqa: B902 (a crashing row must not stop the batch)
        signal.alarm(0)
        return row['va'], {'status': 'error', 'detail': '%s: %s' % (type(ex).__name__, str(ex)[:300])}


def candidates(only):
    entries = json.loads((PROJECT / 'function-ledger.json').read_text())['entries']
    out, refused = [], {}
    for e in entries:
        va = int(e['va'], 16)
        if e['status'] != 'pending' or va < 0x480000 or e['region'] not in ('game', 'crt_mfc'):
            continue
        if only and va not in only and va != 0x50f978:
            continue
        if va == 0x50c920:
            continue                                  # the stack probe is included as the shared helper of the other rows
        out.append((va, e['body_size'] or e['span']))
    return out, refused


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--rows')
    ap.add_argument('--seeds', type=int, default=24)
    ap.add_argument('--jobs', type=int, default=4)
    ap.add_argument('--timeout', type=int, default=120)
    ap.add_argument('--cache', help='JSON file with the finished rows (resumable)')
    ap.add_argument('--out-dir', default=str(PROJECT))
    ap.add_argument('--merge', action='store_true', help='with --rows: keep the other rows of the existing table and C file (FL-58)')
    a = ap.parse_args()
    L.BULK = True
    W.ORIG_PAGE_LIMIT = 1000
    L.INLINE_CALLEES.add(0x50f978)                    # FL-58: __EH_prolog
    spans = L.ledger_spans()
    only = {int(v, 16) for v in a.rows.split(',')} if a.rows else None
    cands, refused = candidates(only)
    texts, rows, lifted = {}, {}, []
    uses_inline = False
    for va, body in cands:
        try:
            text, callees, imports, fs, inline = L.lift(va, body)
        except L.Unsupported as ex:
            refused['0x%x' % va] = str(ex)
            continue
        except Exception as ex:                       # noqa: BLE001
            refused['0x%x' % va] = 'lifter error: %s: %s' % (type(ex).__name__, str(ex)[:120])
            continue
        uses_inline |= bool(inline)
        texts[va] = text
        rows[va] = W.row_info(va, body, callees, imports, fs, L.INDIRECT_SITES.get(va))
        lifted.append(va)
    print('lifted %d of %d candidates; refused %d' % (len(lifted), len(cands), len(refused)), flush=True)
    helper = L.lift(0x50c920, spans[0x50c920])[0] if uses_inline else ''
    results = {}
    cache = Path(a.cache) if a.cache else None
    if cache is not None and cache.is_file():
        results = {int(k, 16): v for k, v in json.loads(cache.read_text()).items()}
    todo = sorted((v for v in lifted if v not in results or (results[v]['status'] in ('error', 'mismatch') and not results[v].get('detail', '').startswith('hang'))), key=lambda v: rows[v]['body'])      # small rows first
    t0 = time.time()
    if todo:
        tmp = tempfile.mkdtemp()
        src = Path(tmp) / 'all.c'
        build_set = list(lifted)
        for attempt in range(6):                      # a row whose C does not compile is taken out and recorded as an error
            head = '#include "original_methods_fl41.h"\nvoid m50f978_lifted(Fl41Regs *r, const Fl41Host *h);\n' + helper
            lines_at, n = {}, head.count('\n') + 1
            for v in build_set:
                lines_at[v] = (n, n + texts[v].count('\n') - 1)       # a lifted text ends with a newline and the join adds one more
                n += texts[v].count('\n') + 1
            src.write_text(head + '\n'.join(texts[v] for v in build_set))
            try:
                W.build_library(tmp, [src])
                break
            except AssertionError as ex:
                import re as _re
                bad = {v for m in _re.finditer(r'all\.c:(\d+):\d+: error', str(ex)) for v, (lo, hi) in lines_at.items() if lo <= int(m.group(1)) <= hi}
                if not bad:
                    raise
                for v in bad:
                    results[v] = {'status': 'error', 'detail': 'C does not compile: ' + str(ex)[:200]}
                build_set = [v for v in build_set if v not in bad]
                todo = [v for v in todo if v not in bad]
                print('dropped %d rows that do not compile' % len(bad), flush=True)
        libpath = str(Path(tmp) / 'fl41.so')
        print('library built, %.0f s' % (time.time() - t0), flush=True)
        with mp.Pool(a.jobs, maxtasksperchild=1) as pool:
            for k, (va, res) in enumerate(pool.imap_unordered(one, [(rows[v], libpath, a.seeds, a.timeout) for v in todo])):
                results[va] = res
                if cache is not None:
                    cache.write_text(json.dumps({hex(x): y for x, y in results.items()}))
                print('%d/%d 0x%x %s %s' % (k + 1, len(todo), va, res['status'], {x: res[x] for x in ('instructions', 'directions') if x in res}), flush=True)
    done = {}
    for v in lifted:
        res = results[v]
        if res['status'] in ('complete', 'incomplete'):
            done[v] = 'agrees' if res['seeds'] else 'no seed'
    out = Path(a.out_dir)
    kept = [v for v in lifted if v in done]
    old_table, old_texts = {}, {}
    if a.merge:
        old_table = json.loads((out / 'tests/fl41_translated.json').read_text())
        import re as _re
        for chunk in _re.split(r'(?=/\* GAME\.EXE 0x)', (out / 'translated/original_methods_fl41_translated.c').read_text()):
            m = _re.match(r'/\* GAME\.EXE 0x([0-9a-f]+)', chunk)
            if m:
                old_texts[int(m.group(1), 16)] = chunk.rstrip('\n') + '\n'
    all_va = sorted(set(kept) | {v for v in old_texts if v not in lifted})
    (out / 'translated/original_methods_fl41_translated.c').write_text(HEADER + helper + '\n'.join(texts[v] if v in texts and v in done else old_texts[v] for v in all_va))
    table = {'0x%x' % v: {'body': rows[v]['body'], 'callees': {hex(k): n for k, n in rows[v]['callees'].items()},
                          'imports': {hex(k): n for k, n in rows[v]['imports'].items()}, 'fs': rows[v]['fs'], 'sites': {hex(k): n for k, n in rows[v].get('sites', {}).items()}, 'frame': bool(results[v].get('frame')), 'status': done[v],
                          'seeds': [[sd, [list(o) for o in ov]] for sd, ov in results[v]['seeds']],
                          'instructions': results[v]['instructions'], 'directions': results[v]['directions']} for v in kept}
    table = {**{k: v for k, v in old_table.items() if int(k, 16) not in lifted}, **table}
    (out / 'tests/fl41_translated.json').write_text(json.dumps(table, indent=1, sort_keys=True) + '\n')
    bad = {'0x%x' % v: results[v] for v in lifted if v not in done}
    (out / 'tasks/fl55-translation-defects.json').write_text(json.dumps({'refused': refused, 'failed': bad}, indent=1, sort_keys=True) + '\n')
    import collections
    print('translated %d (agrees %d, no seed %d); mismatch %d, error %d; refused by the lifter %d, %.0f s'
          % (len(kept), sum(1 for v in kept if done[v] == 'agrees'), sum(1 for v in kept if done[v] == 'no seed'),
             sum(1 for r in bad.values() if r['status'] == 'mismatch'), sum(1 for r in bad.values() if r['status'] == 'error'), len(refused), time.time() - t0))
    print(collections.Counter(__import__('re').sub(r'0x[0-9a-f]+', 'N', v) for v in refused.values()).most_common(12))


if __name__ == '__main__':
    main()
